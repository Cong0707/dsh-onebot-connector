/** id → 名字。查不到返回空串。 */
export function faceName(id) {
  if (id === undefined || id === null || id === '') return '';
  return FACES[String(id)] ?? '';
}

/** 名字 → id。支持精确匹配，也接受 "14" 这种纯数字。查不到返回 null。 */
export function faceIdOf(name) {
  const s = String(name ?? '').trim().replace(/^\//, '');
  if (!s) return null;
  if (/^\d+$/.test(s)) return s;
  for (const [id, n] of Object.entries(FACES)) if (n === s) return id;
  // 退一步：唯一包含匹配
  const hits = Object.entries(FACES).filter(([, n]) => n.includes(s));
  return hits.length === 1 ? hits[0][0] : null;
}

/** 按关键词搜索，返回 [{ id, name }]。query 为空时返回前 limit 个常用表情。 */
export function searchFaces(query, limit = 30) {
  const q = String(query ?? '').trim().replace(/^\//, '');
  const all = Object.entries(FACES).map(([id, name]) => ({ id, name }));
  if (!q) {
    // 空查询：给经典高频表情，按 id 升序
    return all.filter((f) => Number(f.id) <= 105).slice(0, limit);
  }
  return all.filter((f) => f.name.includes(q) || f.id === q).slice(0, limit);
}

